def comp_X_av(e_tmp, phi_tmp):
    Z = 0.
    X_av = 0.
    for i in range(num_sol):
        prob = np.exp(-(e_tmp[i]-e_tmp[0]) / (k_B * Temp))
        Z += prob
        X_av += prob * np.sum(x_int * phi_tmp[:, i] ** 2)
    return X_av / Z

def compute_ground_state_Vpp_and_frequency(
        x_int, v_int, eigen_data_group, mass,
        polar_mode_freq=None,
        field_idx=None,
        field_value=None):
    """
    Compute <V''(x)> using the ground state at a given electric field
    and estimate harmonic frequency.
    """

    dx = x_int[1] - x_int[0]

    # ------------------------------------
    # 5-point stencil second derivative
    # ------------------------------------
    d2Vdx2 = np.zeros_like(v_int)

    for i in range(2, len(v_int)-2):
        d2Vdx2[i] = (
            -v_int[i+2] + 16*v_int[i+1] - 30*v_int[i]
            + 16*v_int[i-1] - v_int[i-2]
        ) / (12 * dx**2)

    valid = slice(2, -2)

    d2Vdx2_valid = d2Vdx2[valid]

    # ------------------------------------
    # Select field
    # ------------------------------------
    if field_idx is None:
        field_idx = int(np.argmin(np.abs(field_values)))

    group = eigen_data_group[f'field_{field_idx:03d}']

    energies = group['energies'][:]
    energies = energies - energies[0]

    eigenvectors = group['eigenvectors'][:]

    psi0 = eigenvectors[:,0]
    psi0_valid = psi0[valid]

    prob = psi0_valid**2

    # ------------------------------------
    # Expectation value <V''>
    # ------------------------------------
    exp_Vpp = np.sum(prob * d2Vdx2_valid) * dx / np.sum(prob * dx)

    # ------------------------------------
    # Harmonic frequency
    # ------------------------------------
    conver = 419.3
    omega = conver*np.sqrt(exp_Vpp / mass)
    nu = omega / (2*np.pi)

    # ------------------------------------
    # Frequency from excitation
    # ------------------------------------
    deltaE = energies[1] - energies[0]

    tol = 1e-4
    degenerate = False

    if abs(deltaE) < tol:
        degenerate = True
        deltaE_original = deltaE
        deltaE = energies[2] - energies[0]

    freq_spacing_thz = deltaE * 1520 / (2*np.pi)

    ratio = nu / freq_spacing_thz

    # ------------------------------------
    # Output
    # ------------------------------------
    if field_value is None:
        print("\n--- Frequency analysis at zero field ---")
    else:
        print(f"\n--- Frequency analysis at E = {field_value:.3f} V/nm ---")

    print(
        f"Harmonic freq (<V''>): {nu:.6f} THz | "
        f"Freq from ΔE: {freq_spacing_thz:.6f} THz | "
        f"Anharmonicity ratio: {ratio:.3f}"
    )

    if degenerate:
        print(
            f"Ground state degenerate within tol={tol} eV "
            f"(E1-E0={deltaE_original:.3e})."
        )
        print("Used E2-E0 for estimate.")

    # ------------------------------------
    # Suggested mass
    # ------------------------------------
    if polar_mode_freq is not None:
        target_nu = polar_mode_freq
        me_per_amu = 1822.888486

        suggested_mass_me = exp_Vpp / ((2*np.pi*target_nu/419.3)**2)
        suggested_mass_amu = suggested_mass_me / me_per_amu

        print("\nTarget polar mode frequency:", target_nu, "THz")
        print(f"Suggested mass: {suggested_mass_amu:.6f} amu = {suggested_mass_me:.2f} me")

    return exp_Vpp, nu



