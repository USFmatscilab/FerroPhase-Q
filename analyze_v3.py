"""
Thermal averaging and polarization analysis from quantum eigenstate data.

This script analyzes eigenstates generated by `generate.py` to compute
thermal averages of position and polarization as a function of electric field.
Optional analysis can estimate the harmonic frequency of the potential well
and suggest a mass that reproduces a target polar mode frequency.

## FUNCTIONALITY

1. Loads simulation results from `all_simulation_data.h5`

   * Eigenenergies and eigenfunctions
   * Physical parameters: mass, number of states, effective charge (z*), volume
   * Electric field values

2. Loads the potential energy grid from `interpolated_potential.txt`.

3. Loads analysis parameters from `PARAMS_anal.json`.

4. Computes thermal averages

   * Full thermal average ⟨x⟩
   * Optional partial average ⟨x⟩ within [x_min, x_max]

5. Converts ⟨x⟩ to polarization using
   P = ⟨x⟩ / conv_P2x

6. Plots polarization vs electric field.

7. Optionally plots eigenstates contributing ≥99% of the thermal probability
   at a user-selected electric field.

8. Optional frequency analysis (enabled by `do_frequency_analysis`)

   * Computes ⟨V''⟩ using the ground-state wavefunction
   * Estimates harmonic frequency of the potential well
   * Compares with the E1–E0 excitation spacing
   * Reports anharmonicity ratio
   * If `polar_mode_freq_THz` is provided, suggests a mass reproducing
     that frequency (output in me and amu).

## INPUT FILES

all_simulation_data.h5
Eigenvalues, eigenvectors, and simulation parameters.

interpolated_potential.txt
Potential grid with columns:
x   V(x)

PARAMS_anal.json
Analysis parameters, e.g.
{
"Temp": float,
"x_min": float (optional),
"x_max": float (optional),
"Field_to_plot": float (optional),
"do_frequency_analysis": bool (optional),
"polar_mode_freq_THz": float (optional)
}

## OUTPUT

Polarization_vs_Field_equil.png
Polarization vs electric field.

Polarization_vs_Field_equil.txt
Field(V/nm)   P_full(C/m²)

Eigenstates_99percent.png
Eigenstates contributing ≥99% thermal probability (optional).

prob_density_selected_states.txt
Probability densities of selected eigenstates (optional).

## NOTES

Eigenvalues used in plots are shifted so the ground-state energy is zero,
so reported frequencies correspond to excitations relative to the ground state.
"""



